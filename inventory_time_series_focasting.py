## create function for inventory simulations
def simulate_inventory(demand_paths, starting_inventory, lead_time, policy):

    n_simulations, horizon = demand_paths.shape
    ending_inventory = []

    stockout_count = 0
    total_stockout_days = 0

    for sim in range(n_simulations):
        inventory = starting_inventory
        pending_order = None
        had_stockout = False

        for day in range(horizon):
            # 1. Receive order if it arrives today
            if pending_order is not None:
                if pending_order["arrival_day"] == day:
                    inventory += pending_order["quantity"]
                    pending_order = None

            # 2. Today's demand
            demand = demand_paths[sim, day]
            if demand > inventory:
                # stockout happens
                had_stockout = True
                total_stockout_days += 1
                inventory = 0
            else:
                inventory -= demand

            # 3. Place order according to policy
            if policy["type"] == "periodic": ## policy A
                if day % policy["interval"] == 0:
                    pending_order = {
                        "arrival_day": day + lead_time,
                        "quantity": policy["order_qty"]}

            elif policy["type"] == "reorder_point": ## policy B
                if inventory < policy["s"]:
                    order_quantity = policy["S"] - inventory
                    pending_order = {
                        "arrival_day": day + lead_time,
                        "quantity": order_quantity}

        if had_stockout:
            stockout_count += 1

        ending_inventory.append(inventory)

    return {
        "percent_simulations_with_stockout": stockout_count / n_simulations * 100,
        "average_daily_stockout_rate": total_stockout_days / (n_simulations*horizon),
        "average_ending_inventory": np.mean(ending_inventory)
}

