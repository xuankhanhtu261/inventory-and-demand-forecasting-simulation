## Policy B (vary reorder threshold s, keep S fixed)
# s is currently: avg_demand * lead_time + k * resid_std, where k=1.65 (a ~95% service-level z-score)
# Let's vary k instead of an absolute number, since it's more interpretable (bigger k = bigger safety margin)

k_values_to_test = [0.5, 1.0, 1.65, 2.0, 2.33]  # roughly corresponds to ~70%, ~84%, ~95%, ~98%, ~99% service levels
fixed_S_days = 5  # hold target level constant while we vary the threshold

